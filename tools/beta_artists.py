# Новые художники для тестового стенда -> ../data/beta-extra.js (дополняет PAINTINGS и PORTRAITS только на стенде).
# Логика та же, что в resolve.py + fetch.py + build.py + portraits.py, но для короткого списка и в отдельный файл.
import json, urllib.request, urllib.parse, time, hashlib, random, re
NAMES = ['Pieter de Hooch', 'Jan Steen', 'Gerard ter Borch', 'William Hogarth', 'Pietro Longhi', 'Jean-Baptiste Greuze']
UA = {'User-Agent': 'ArtEyeTrainer/0.1 (personal learning app)', 'Accept': 'application/sparql-results+json'}
def sparql(q):
    data = urllib.parse.urlencode({'query': q}).encode()
    for i in range(8):
        try:
            return json.load(urllib.request.urlopen(urllib.request.Request('https://query.wikidata.org/sparql', data=data, headers=UA), timeout=120))['results']['bindings']
        except Exception as e:
            print('  retry', e, flush=True); time.sleep(20)
    raise SystemExit('failed')

# 1. QID: среди людей с таким именем — у кого больше картин
vals = ' '.join('"%s"@en' % n for n in NAMES)
rows = sparql('''SELECT ?name ?a (COUNT(DISTINCT ?p) AS ?n) WHERE { VALUES ?name { %s }
 ?a rdfs:label|skos:altLabel ?name. ?a wdt:P31 wd:Q5. ?p wdt:P170 ?a; wdt:P18 []; wdt:P31 wd:Q3305213 } GROUP BY ?name ?a''' % vals)
best = {}
for b in rows:
    n, c, a = b['name']['value'], int(b['n']['value']), b['a']['value'].split('/')[-1]
    if n not in best or c > best[n][1]: best[n] = (a, c)
print(best)

# 2. картины — тот же запрос, что в fetch.py; 3. отбор — как в build.py
MAX, FAMOUS, MIN = 70, 15, 18
random.seed(42)
P = {}
for n in NAMES:
    qid = best[n][0]; time.sleep(1.5)
    rows = sparql(f'''SELECT ?p (SAMPLE(?img) AS ?img) (MIN(YEAR(?d)) AS ?y) (SAMPLE(?ru) AS ?ru) (SAMPLE(?en) AS ?en) (SAMPLE(?sl) AS ?sl) WHERE {{
 ?p p:P170 ?st. ?st ps:P170 wd:{qid}. FILTER NOT EXISTS {{ ?st pq:P5102 [] }} FILTER NOT EXISTS {{ ?st pq:P1774 [] }}
 ?p wdt:P31 wd:Q3305213. ?p wdt:P18 ?img. OPTIONAL {{ ?p wdt:P571 ?d }}
 FILTER NOT EXISTS {{ ?p wdt:P170 ?other. FILTER(?other != wd:{qid}) }}
 OPTIONAL {{ ?p rdfs:label ?ru FILTER(LANG(?ru)="ru") }} OPTIONAL {{ ?p rdfs:label ?en FILTER(LANG(?en)="en") }}
 OPTIONAL {{ ?p wikibase:sitelinks ?sl }} }} GROUP BY ?p''')
    seen, items = set(), []
    for r in rows:
        r = {k: v['value'] for k, v in r.items()}
        f = urllib.parse.unquote(r['img'].split('FilePath/')[-1]).replace(' ', '_')
        if f.rsplit('.', 1)[-1].lower() not in ('jpg', 'jpeg', 'png', 'tif', 'tiff') or f in seen: continue
        seen.add(f)
        title = r.get('ru') or r.get('en') or ''
        if re.fullmatch(r'Q\d+', title): title = ''
        y = int(r['y']) if r.get('y') and r['y'].lstrip('-').isdigit() else None
        items.append({'f': f, 'h': hashlib.md5(f.encode()).hexdigest()[:2], 'y': y, 't': title, 'sl': int(r.get('sl') or 0)})
    print(n, qid, len(items), 'картин')
    if len(items) < MIN: continue
    items.sort(key=lambda x: -x['sl'])
    fam, rest = items[:FAMOUS], items[FAMOUS:]; random.shuffle(rest)
    P[qid] = [[p['h'], p['f'], p['y'], p['t'], 1 if i < FAMOUS else 0] for i, p in enumerate(fam + rest[:MAX - FAMOUS])]

# 4. портреты
rows = sparql('SELECT ?a (SAMPLE(?img) AS ?img) WHERE { VALUES ?a { %s } ?a wdt:P18 ?img } GROUP BY ?a' % ' '.join('wd:' + q for q in P))
POR = {}
for r in rows:
    f = urllib.parse.unquote(r['img']['value'].split('FilePath/')[-1]).replace(' ', '_')
    POR[r['a']['value'].split('/')[-1]] = [hashlib.md5(f.encode()).hexdigest()[:2], f]
js = ('// generated by tools/beta_artists.py: художники только для тестового стенда\n'
      'Object.assign(window.PAINTINGS, ' + json.dumps(P, ensure_ascii=False, separators=(',', ':')) + ');\n'
      'Object.assign(window.PORTRAITS, ' + json.dumps(POR, ensure_ascii=False, separators=(',', ':')) + ');\n')
open('../data/beta-extra.js', 'w', encoding='utf-8').write(js)
print({n: (best[n][0], len(P.get(best[n][0], []))) for n in NAMES}, 'portraits', len(POR))
