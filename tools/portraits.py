# Портреты художников (Wikidata P18) -> ../data/portraits.js : {qid: [md5prefix, commonsFile]}
import json, re, hashlib, urllib.parse, urllib.request
src = open('../js/curriculum.js', encoding='utf-8').read()
qids = sorted(set(re.findall(r"\{ q: '(Q\d+)'", src)))
q = 'SELECT ?a (SAMPLE(?img) AS ?img) WHERE { VALUES ?a { %s } ?a wdt:P18 ?img } GROUP BY ?a' % ' '.join('wd:' + x for x in qids)
req = urllib.request.Request('https://query.wikidata.org/sparql', data=urllib.parse.urlencode({'query': q}).encode(),
      headers={'User-Agent': 'ArtEyeTrainer/0.1 (personal learning app)', 'Accept': 'application/sparql-results+json'})
rows = json.load(urllib.request.urlopen(req, timeout=120))['results']['bindings']
out = {}
for r in rows:
    f = urllib.parse.unquote(r['img']['value'].split('FilePath/')[-1]).replace(' ', '_')
    out[r['a']['value'].split('/')[-1]] = [hashlib.md5(f.encode()).hexdigest()[:2], f]
open('../data/portraits.js', 'w', encoding='utf-8').write('// generated by tools/portraits.py; [md5prefix, commonsFile]\nwindow.PORTRAITS=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(qids), 'artists,', len(out), 'portraits; missing:', [x for x in qids if x not in out])
