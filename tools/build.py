# raw.json (Wikidata) -> ../data/paintings.js : compact per-artist painting lists
import json, hashlib, random, urllib.parse, re
raw=json.load(open('raw.json',encoding='utf-8'))
MAX=70; FAMOUS=15; MIN=18
random.seed(42)
out={}
for name,d in raw.items():
    seen=set(); items=[]
    for r in d['rows']:
        f=urllib.parse.unquote(r['img'].split('FilePath/')[-1]).replace(' ','_')
        ext=f.rsplit('.',1)[-1].lower()
        if ext not in ('jpg','jpeg','png','tif','tiff') or f in seen: continue
        seen.add(f)
        title=r.get('ru') or r.get('en') or ''
        if re.fullmatch(r'Q\d+',title): title=''
        y=int(r['y']) if r.get('y') and r['y'].lstrip('-').isdigit() else None
        h=hashlib.md5(f.encode()).hexdigest()[:2]
        items.append({'f':f,'h':h,'y':y,'t':title,'sl':int(r.get('sl') or 0)})
    if len(items)<MIN: print('skip',name,len(items)); continue
    items.sort(key=lambda x:-x['sl'])
    famous=items[:FAMOUS]; rest=items[FAMOUS:]; random.shuffle(rest)
    pick=famous+rest[:MAX-FAMOUS]
    out[d['qid']]=[[p['h'],p['f'],p['y'],p['t'],1 if i<FAMOUS else 0] for i,p in enumerate(pick)]
    print(len(pick),name)
js='// generated by tools/build.py from Wikidata; [md5prefix, commonsFile, year, title, famous]\nwindow.PAINTINGS='+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n'
open('../data/paintings.js','w',encoding='utf-8').write(js)
print('artists',len(out),'paintings',sum(map(len,out.values())),'bytes',len(js.encode()))
